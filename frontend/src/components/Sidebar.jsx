function TabGroup({ group, isExpanded, onToggle }) {
  return (
    <div className="mb-1">
      <button
        onClick={onToggle}
        className="w-full flex items-center justify-between px-3 py-2 text-xs font-semibold text-gray-400 hover:text-gray-300 uppercase tracking-wider"
      >
        <span>{group.label}</span>
        {isExpanded ? icons.chevronDown : icons.chevronRight}
      </button>

      {isExpanded && (
        <div className="space-y-0.5">
          {group.tabs.map((tab) => (
            <NavLink
              key={tab.id}
              to={tab.path}
              className={({ isActive }) =>
                `flex items-center gap-3 px-3 py-2 mx-2 rounded-md text-sm transition-colors ${
                  isActive
                    ? 'bg-indigo-600 text-white'
                    : 'text-gray-300 hover:bg-gray-700/50 hover:text-white'
                }`
              }
            >
              {tab.icon}
              <span>{tab.label}</span>
            </NavLink>
          ))}
        </div>
      )}
    </div>
  );
}

export default function Sidebar() {
  const navigate = useNavigate();
  const [expandedGroups, setExpandedGroups] = useState({
    chat: true,
    channels: true,
    system: true,
    settings: true,
  });

  const toggleGroup = (groupId) => {
    setExpandedGroups((prev) => ({
      ...prev,
      [groupId]: !prev[groupId],
    }));
  };

  const handleLogout = () => {
    auth.logout();
    navigate('/login');
  };

  return (
    <aside className="w-56 bg-gray-800 border-r border-gray-700 flex flex-col h-full">
      {/* Logo */}
      <div className="h-14 flex items-center gap-2 px-4 border-b border-gray-700">
        <img src="/ungula_logo.png" alt="Ungula" className="w-8 h-8 rounded" />
        <span className="text-xl font-bold text-indigo-400">Ungula</span>
      </div>

      {/* Navigation */}
      <nav className="flex-1 py-4 overflow-y-auto scrollbar-thin">
        {tabGroups.map((group) => (
          <TabGroup
            key={group.id}
            group={group}
            isExpanded={expandedGroups[group.id]}
            onToggle={() => toggleGroup(group.id)}
          />
        ))}
      </nav>

      {/* Logout */}
      <div className="border-t border-gray-700 p-2">
        <button
          onClick={handleLogout}
          className="w-full flex items-center gap-3 px-3 py-2 rounded-md text-sm text-gray-400 hover:bg-gray-700/50 hover:text-white transition-colors"
        >
          {icons.logout}
          <span>Logout</span>
        </button>
      </div>
    </aside>
  );
}
